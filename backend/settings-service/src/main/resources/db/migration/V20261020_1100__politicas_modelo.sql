## 1. Quiénes somos

Esta tienda en línea es operada por el proveedor cuya razón social, RUC y dirección fiscal figuran en el pie de página y en el Libro de Reclamaciones. Al usar este sitio aceptas estos términos y condiciones.

## 2. Tu cuenta

Para comprar debes registrarte con datos verdaderos. Eres responsable de la confidencialidad de tu contraseña y de lo que se haga con tu cuenta. Si notas un uso no autorizado, avísanos de inmediato.

## 3. Productos, precios y pagos

- Los precios están expresados en soles (PEN) e incluyen el IGV.
- Las fotografías son referenciales; el color puede variar ligeramente según tu pantalla.
- Puedes pagar con los medios habilitados en la tienda (tarjeta, Yape o Mercado Pago). El pago se procesa en la plataforma de cada medio: la tienda no guarda los datos de tu tarjeta.
- Un pedido queda confirmado cuando recibimos tu pago.

## 4. Stock y reserva

Al iniciar el pago reservamos el stock de tu pedido por un tiempo limitado. Si no pagas dentro de ese plazo, el pedido expira y el stock vuelve a estar disponible.

