## 1. Quién trata tus datos

El titular del banco de datos es el proveedor cuya razón social, RUC y dirección fiscal figuran en el pie de página. Tratamos tus datos personales conforme a la Ley N.° 29733, Ley de Protección de Datos Personales, y su reglamento.

## 2. Qué datos recopilamos

- **Datos de tu cuenta:** nombres, apellidos, documento de identidad, correo electrónico y teléfono.
- **Datos de entrega:** direcciones y distrito de destino.
- **Datos de tus compras:** productos, montos y estado de tus pedidos.
- **Datos del Libro de Reclamaciones:** los que consignas en tu reclamo o queja.

No guardamos los datos de tu tarjeta: el pago lo procesa la plataforma de pagos que elijas.

## 3. Para qué los usamos

Usamos tus datos para crear tu cuenta, procesar y entregar tus pedidos, comunicarnos contigo sobre ellos, atender tus reclamos y cumplir obligaciones legales y tributarias. Solo te enviaremos promociones si lo aceptas expresamente y puedes retirar ese consentimiento cuando quieras.

## 4. A quién los comunicamos

Compartimos lo estrictamente necesario con las plataformas de pago, las empresas de transporte que entregan tus pedidos y los proveedores de correo que nos ayudan a enviarte notificaciones. No vendemos tus datos.

## 5. Cuánto tiempo los conservamos

Los conservamos mientras mantengas tu cuenta y durante los plazos exigidos por la ley (por ejemplo, tributarios y los del Libro de Reclamaciones).

## 6. Tus derechos

Puedes ejercer tus derechos de acceso, rectificación, cancelación y oposición escribiendo al correo de contacto de la tienda, adjuntando una copia de tu documento de identidad. Responderemos dentro de los plazos de la ley.

## 7. Seguridad

Aplicamos medidas técnicas y organizativas razonables para proteger tus datos contra pérdida, acceso o uso no autorizado.

## 8. Menores de edad

Las compras están dirigidas a mayores de edad. Si eres menor, debes contar con la autorización de tu padre, madre o apoderado.

## 9. Cambios en esta política

Podemos actualizar esta política. Cada versión tiene un número y una fecha, y guardamos la versión que aceptaste al registrarte.
