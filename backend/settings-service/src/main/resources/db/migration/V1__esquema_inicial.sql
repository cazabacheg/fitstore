-- settings_db: esquema inicial (micro settings, sección 3.1)
-- Módulos: configuración de tienda, ubigeo (INEI) y Libro de Reclamaciones.

-- ---------------------------------------------------------------------------------------------
-- Extensiones y función auxiliar para el buscador de distritos sin tildes
-- ---------------------------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS unaccent;

-- unaccent() no es IMMUTABLE y un índice solo admite funciones inmutables: este envoltorio lo es
-- porque el diccionario 'unaccent' no cambia durante la vida de la base.
CREATE OR REPLACE FUNCTION f_unaccent(texto text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
    RETURN public.unaccent('public.unaccent'::regdictionary, texto);

-- ---------------------------------------------------------------------------------------------
-- Configuración de tienda (singleton: una sola fila con id = 1)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE configuracion_tienda (
    id                        integer      PRIMARY KEY,
    -- identidad
    nombre                    varchar(60)  NOT NULL,
    eslogan                   varchar(120),
    razon_social              varchar(150) NOT NULL,
    ruc                      varchar(11)    NOT NULL,
    direccion_fiscal          varchar(200) NOT NULL,
    -- tema: los cinco colores
    color_primario           varchar(7)      NOT NULL,
    color_secundario         varchar(7)      NOT NULL,
    color_acento             varchar(7)      NOT NULL,
    color_fondo              varchar(7)      NOT NULL,
    color_texto              varchar(7)      NOT NULL,
    -- contenido
    hero_titulo               varchar(80)  NOT NULL,
    hero_subtitulo            varchar(160),
    hero_cta_texto            varchar(30),
    hero_cta_enlace           varchar(300),
    beneficios                jsonb        NOT NULL DEFAULT '[]'::jsonb,
    email                     varchar(150),
    telefono                  varchar(15),
    whatsapp                  varchar(9),
    instagram_url             varchar(300),
    facebook_url              varchar(300),
    tiktok_url                varchar(300),
    horario                   varchar(120),
    tienda_direccion          varchar(200),
    tienda_ubigeo             varchar(6),
    tienda_referencia         varchar(200),
    -- parámetros
    metodos_pago              text[]       NOT NULL,
    modalidades_entrega       text[]       NOT NULL,
    expiracion_pedido_minutos integer      NOT NULL DEFAULT 30,
    dias_reembolso_postventa  integer      NOT NULL DEFAULT 30,
    correos_alertas           text[]       NOT NULL,
    -- control
    version                   integer      NOT NULL DEFAULT 0,
    actualizado_en            timestamptz  NOT NULL DEFAULT now(),
    actualizado_por           varchar(64),
    CONSTRAINT ck_configuracion_unica CHECK (id = 1),
    CONSTRAINT ck_ruc CHECK (ruc ~ '^[0-9]{11}$'),
    CONSTRAINT ck_color_primario CHECK (color_primario ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_color_secundario CHECK (color_secundario ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_color_acento CHECK (color_acento ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_color_fondo CHECK (color_fondo ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_color_texto CHECK (color_texto ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_beneficios CHECK (jsonb_typeof(beneficios) = 'array' AND jsonb_array_length(beneficios) <= 3),
    CONSTRAINT ck_metodos_pago CHECK (cardinality(metodos_pago) >= 1
        AND metodos_pago <@ ARRAY['CULQI', 'YAPE', 'MERCADO_PAGO']),
    CONSTRAINT ck_modalidades_entrega CHECK (cardinality(modalidades_entrega) >= 1
        AND modalidades_entrega <@ ARRAY['DELIVERY_LOCAL', 'AGENCIA', 'RECOJO']),
    CONSTRAINT ck_expiracion_pedido CHECK (expiracion_pedido_minutos BETWEEN 10 AND 120),
    CONSTRAINT ck_dias_reembolso CHECK (dias_reembolso_postventa BETWEEN 0 AND 365),
    CONSTRAINT ck_correos_alertas CHECK (cardinality(correos_alertas) BETWEEN 1 AND 5)
);

CREATE TABLE imagen_tienda (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo              varchar(20)  NOT NULL,
    clave             varchar(200) NOT NULL,
    orden             integer      NOT NULL DEFAULT 0,
    texto_alternativo varchar(200),
    enlace            varchar(300),
    creado_en         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_imagen_tipo CHECK (tipo IN ('LOGO_CLARO', 'LOGO_OSCURO', 'FAVICON', 'LANDING'))
);
-- Una sola imagen por tipo salvo la landing (carrusel)
CREATE UNIQUE INDEX ux_imagen_tipo_unico ON imagen_tienda (tipo) WHERE tipo <> 'LANDING';

CREATE TABLE politica (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          varchar(30) NOT NULL,
    version       integer     NOT NULL,
    contenido     text        NOT NULL,
    publicada_en  timestamptz NOT NULL DEFAULT now(),
    publicada_por varchar(64),
    CONSTRAINT ck_politica_tipo CHECK (tipo IN ('TERMINOS', 'PRIVACIDAD', 'CAMBIOS_DEVOLUCIONES', 'ENVIOS')),
    CONSTRAINT ck_politica_version CHECK (version >= 1),
    CONSTRAINT ux_politica_tipo_version UNIQUE (tipo, version)
);

-- ---------------------------------------------------------------------------------------------
-- Ubigeo (INEI): solo lectura, se carga por migración (V2)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE departamento (
    codigo char(2)      PRIMARY KEY,
    nombre varchar(100) NOT NULL
);

CREATE TABLE provincia (
    codigo              char(4)      PRIMARY KEY,
    departamento_codigo char(2)      NOT NULL REFERENCES departamento (codigo),
    nombre              varchar(100) NOT NULL
);
CREATE INDEX ix_provincia_departamento ON provincia (departamento_codigo);

CREATE TABLE distrito (
    codigo           char(6)      PRIMARY KEY,
    provincia_codigo char(4)      NOT NULL REFERENCES provincia (codigo),
    nombre           varchar(100) NOT NULL
);
CREATE INDEX ix_distrito_provincia ON distrito (provincia_codigo);
-- Buscador de distritos sin tildes
CREATE INDEX ix_distrito_nombre_trgm ON distrito USING gin (f_unaccent(nombre) gin_trgm_ops);

-- ---------------------------------------------------------------------------------------------
-- Libro de Reclamaciones
-- ---------------------------------------------------------------------------------------------
CREATE TABLE reclamo (
    id                 bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             varchar(20)   NOT NULL,
    anio               integer       NOT NULL,
    correlativo        integer       NOT NULL,
    tipo               varchar(10)   NOT NULL,
    estado             varchar(20)   NOT NULL,
    -- consumidor
    nombres            varchar(80)   NOT NULL,
    apellidos          varchar(80)   NOT NULL,
    tipo_documento     varchar(3)    NOT NULL,
    numero_documento   varchar(12)   NOT NULL,
    domicilio          varchar(200)  NOT NULL,
    telefono           varchar(15)   NOT NULL,
    email              varchar(150)  NOT NULL,
    es_menor           boolean       NOT NULL DEFAULT false,
    apoderado_nombre   varchar(160),
    -- bien contratado
    bien_tipo          varchar(10)   NOT NULL,
    bien_descripcion   varchar(300)  NOT NULL,
    monto_reclamado    numeric(12,2),
    pedido_codigo      varchar(20),
    detalle            text          NOT NULL,
    pedido_consumidor  text          NOT NULL,
    fecha_limite       date          NOT NULL,
    respuesta          text,
    respondido_en      timestamptz,
    respondido_por     varchar(64),
    ip                 varchar(45),
    creado_en          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ux_reclamo_numero UNIQUE (numero),
    CONSTRAINT ux_reclamo_anio_correlativo UNIQUE (anio, correlativo),
    CONSTRAINT ck_reclamo_tipo CHECK (tipo IN ('RECLAMO', 'QUEJA')),
    CONSTRAINT ck_reclamo_estado CHECK (estado IN ('REGISTRADO', 'EN_ATENCION', 'RESPONDIDO')),
    CONSTRAINT ck_reclamo_tipo_documento CHECK (tipo_documento IN ('DNI', 'CE')),
    CONSTRAINT ck_reclamo_bien_tipo CHECK (bien_tipo IN ('PRODUCTO', 'SERVICIO')),
    CONSTRAINT ck_reclamo_monto CHECK (monto_reclamado IS NULL OR monto_reclamado >= 0),
    CONSTRAINT ck_reclamo_apoderado CHECK (NOT es_menor OR (apoderado_nombre IS NOT NULL AND apoderado_nombre <> ''))
);
CREATE INDEX ix_reclamo_estado_fecha_limite ON reclamo (estado, fecha_limite);
CREATE INDEX ix_reclamo_creado_en ON reclamo (creado_en);
CREATE INDEX ix_reclamo_numero_documento ON reclamo (numero_documento);

-- Contador por año: INSERT … ON CONFLICT … RETURNING es atómico y no deja huecos (se revierte con la transacción)
CREATE TABLE correlativo_reclamo (
    anio   integer PRIMARY KEY,
    ultimo integer NOT NULL
);

-- ---------------------------------------------------------------------------------------------
-- Eventos (ADR-009): tipos que espera fitstore-common (infraestructura 10.3)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE outbox_evento (
    id           uuid         PRIMARY KEY,
    tipo         varchar(100) NOT NULL,
    agregado_id  varchar(64)  NOT NULL,
    payload      jsonb        NOT NULL,
    creado_en    timestamptz  NOT NULL,
    publicado_en timestamptz
);
CREATE INDEX ix_outbox_pendientes ON outbox_evento (creado_en) WHERE publicado_en IS NULL;

-- settings no consume eventos, pero la autoconfiguración de mensajería valida esta entidad (regla común de 0a)
CREATE TABLE evento_procesado (
    evento_id    uuid        PRIMARY KEY,
    procesado_en timestamptz NOT NULL
);
