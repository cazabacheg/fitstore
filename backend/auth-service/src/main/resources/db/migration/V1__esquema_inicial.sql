-- auth_db: esquema inicial de auth-service (micro auth, sección 3.1) y tablas de eventos de fitstore-common (ADR-009).
-- Sin semillas ni contraseñas: el primer ADMIN se crea al arrancar desde variables de entorno (D6).

CREATE TABLE cliente (
    id                           uuid         PRIMARY KEY,
    email                        varchar(254) NOT NULL,
    password_hash                varchar(60)  NOT NULL,
    nombres                      varchar(80)  NOT NULL,
    apellidos                    varchar(80)  NOT NULL,
    dni                          char(8)      NOT NULL UNIQUE,
    telefono                     varchar(15)  NOT NULL,
    activo                       boolean      NOT NULL DEFAULT true,
    credenciales_actualizadas_en timestamptz  NOT NULL,
    ultimo_login_en              timestamptz,
    creado_en                    timestamptz  NOT NULL,
    actualizado_en               timestamptz  NOT NULL,
    version                      integer,
    CONSTRAINT ck_cliente_dni CHECK (dni ~ '^[0-9]{8}$')
);
CREATE UNIQUE INDEX ux_cliente_email ON cliente (lower(email));

CREATE TABLE staff (
    id                           uuid         PRIMARY KEY,
    email                        varchar(254) NOT NULL,
    password_hash                varchar(60),
    nombres                      varchar(80)  NOT NULL,
    apellidos                    varchar(80)  NOT NULL,
    rol                          varchar(20)  NOT NULL,
    activo                       boolean      NOT NULL DEFAULT true,
    credenciales_actualizadas_en timestamptz  NOT NULL,
    ultimo_login_en              timestamptz,
    creado_en                    timestamptz  NOT NULL,
    actualizado_en               timestamptz  NOT NULL,
    version                      integer,
    creado_por                   uuid         REFERENCES staff (id),
    CONSTRAINT ck_staff_rol CHECK (rol IN ('OPERADOR', 'ADMIN'))
);
CREATE UNIQUE INDEX ux_staff_email ON staff (lower(email));

CREATE TABLE direccion (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id        uuid         NOT NULL REFERENCES cliente (id),
    alias             varchar(40)  NOT NULL,
    ubigeo            char(6)      NOT NULL,
    direccion         varchar(200) NOT NULL,
    referencia        varchar(200),
    telefono_contacto varchar(15),
    predeterminada    boolean      NOT NULL,
    creado_en         timestamptz  NOT NULL,
    actualizado_en    timestamptz  NOT NULL,
    CONSTRAINT ck_direccion_ubigeo CHECK (ubigeo ~ '^[0-9]{6}$')
);
CREATE INDEX ix_direccion_cliente ON direccion (cliente_id);
CREATE UNIQUE INDEX ux_direccion_predeterminada ON direccion (cliente_id) WHERE predeterminada;

CREATE TABLE consentimiento (
    id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       uuid        NOT NULL REFERENCES cliente (id),
    tipo             varchar(20) NOT NULL,
    version_politica varchar(20) NOT NULL,
    aceptado_en      timestamptz NOT NULL,
    ip               varchar(45) NOT NULL,
    CONSTRAINT ck_consentimiento_tipo CHECK (tipo IN ('TERMINOS', 'PRIVACIDAD'))
);
CREATE INDEX ix_consentimiento_cliente ON consentimiento (cliente_id);

CREATE TABLE token_password (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id uuid        REFERENCES cliente (id),
    staff_id   uuid        REFERENCES staff (id),
    token_hash char(64)    NOT NULL UNIQUE,
    motivo     varchar(20) NOT NULL,
    expira_en  timestamptz NOT NULL,
    usado_en   timestamptz,
    creado_en  timestamptz NOT NULL,
    CONSTRAINT ck_token_password_motivo CHECK (motivo IN ('RECUPERACION', 'INVITACION')),
    -- exactamente uno de los dos dueños
    CONSTRAINT ck_token_password_dueno CHECK ((cliente_id IS NULL) <> (staff_id IS NULL))
);
CREATE INDEX ix_token_password_cliente ON token_password (cliente_id);
CREATE INDEX ix_token_password_staff ON token_password (staff_id);

-- Tipos que espera fitstore-common (infraestructura 10.3)
CREATE TABLE outbox_evento (
    id           uuid         PRIMARY KEY,
    tipo         varchar(100) NOT NULL,
    agregado_id  varchar(64)  NOT NULL,
    payload      jsonb        NOT NULL,
    creado_en    timestamptz  NOT NULL,
    publicado_en timestamptz
);
CREATE INDEX ix_outbox_pendientes ON outbox_evento (creado_en) WHERE publicado_en IS NULL;

CREATE TABLE evento_procesado (
    evento_id    uuid        PRIMARY KEY,
    procesado_en timestamptz NOT NULL
);
