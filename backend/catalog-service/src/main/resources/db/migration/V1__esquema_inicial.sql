-- catalog_db: esquema inicial (micro catalog-service, sección 3.1). Módulo catálogo + módulo inventario + eventos.
-- Montos en NUMERIC(10,2), soles con IGV incluido (D8). Borrado lógico con "activo" (ADR-015).
-- Las unicidades con una columna opcional usan NULLS NOT DISTINCT (PostgreSQL 15+) para que dos raíces o dos
-- tramos globales iguales también choquen.

CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- unaccent() no es IMMUTABLE y no se puede indexar; este envoltorio fija el diccionario y sí lo es.
-- La búsqueda de productos usa f_unaccent(lower(nombre)) para que el índice trigram se aproveche.
CREATE FUNCTION f_unaccent(texto text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
    AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, texto) $$;

-- ============================ Módulo catálogo ============================

CREATE TABLE categoria (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    padre_id      bigint       REFERENCES categoria (id),
    nombre        varchar(80)  NOT NULL,
    slug          varchar(100) NOT NULL,
    orden         integer      NOT NULL DEFAULT 0,
    activo        boolean      NOT NULL DEFAULT true,
    creado_en     timestamptz  NOT NULL,
    actualizado_en timestamptz NOT NULL,
    CONSTRAINT uq_categoria_slug UNIQUE (slug)
);
-- Nombre único entre hermanas (las raíces son hermanas entre sí: padre_id NULL cuenta como igual)
CREATE UNIQUE INDEX uq_categoria_hermanas ON categoria (padre_id, lower(nombre)) NULLS NOT DISTINCT;
CREATE INDEX ix_categoria_padre ON categoria (padre_id);

CREATE TABLE talla (
    id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(10) NOT NULL,
    orden  integer     NOT NULL,
    activo boolean     NOT NULL DEFAULT true,
    CONSTRAINT uq_talla_codigo UNIQUE (codigo)
);

CREATE TABLE color (
    id     bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(40) NOT NULL,
    hex    char(7)     NOT NULL,
    activo boolean     NOT NULL DEFAULT true,
    CONSTRAINT ck_color_hex CHECK (hex ~ '^#[0-9A-Fa-f]{6}$')
);
CREATE UNIQUE INDEX uq_color_nombre ON color (lower(nombre));

CREATE TABLE producto (
    id              bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          varchar(20)   NOT NULL,
    nombre          varchar(150)  NOT NULL,
    slug            varchar(180)  NOT NULL,
    descripcion     text,
    precio_base     numeric(10,2) NOT NULL,
    precio_desde    numeric(10,2) NOT NULL,
    estado          varchar(20)   NOT NULL DEFAULT 'BORRADOR',
    destacado       boolean       NOT NULL DEFAULT false,
    orden_destacado integer,
    modo_descuento  varchar(20)   NOT NULL DEFAULT 'GLOBAL',
    creado_en       timestamptz   NOT NULL,
    actualizado_en  timestamptz   NOT NULL,
    version         integer       NOT NULL DEFAULT 0,
    CONSTRAINT uq_producto_slug UNIQUE (slug),
    CONSTRAINT uq_producto_codigo UNIQUE (codigo),
    CONSTRAINT ck_producto_estado CHECK (estado IN ('BORRADOR', 'ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_producto_modo_descuento CHECK (modo_descuento IN ('GLOBAL', 'PERSONALIZADO', 'SIN_DESCUENTO'))
);
CREATE INDEX ix_producto_nombre_trgm ON producto USING gin (f_unaccent(lower(nombre)) gin_trgm_ops);
CREATE INDEX ix_producto_estado ON producto (estado);
CREATE INDEX ix_producto_precio_desde ON producto (precio_desde);
CREATE INDEX ix_producto_creado_en ON producto (creado_en);

CREATE TABLE producto_categoria (
    producto_id  bigint NOT NULL REFERENCES producto (id),
    categoria_id bigint NOT NULL REFERENCES categoria (id),
    PRIMARY KEY (producto_id, categoria_id)
);
CREATE INDEX ix_producto_categoria_categoria ON producto_categoria (categoria_id);

CREATE TABLE variante (
    id             bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id    bigint        NOT NULL REFERENCES producto (id),
    talla_id       bigint        NOT NULL REFERENCES talla (id),
    color_id       bigint        NOT NULL REFERENCES color (id),
    sku            varchar(60)   NOT NULL,
    precio         numeric(10,2),             -- NULL = usa el precio base del producto
    activo         boolean       NOT NULL DEFAULT true,
    creado_en      timestamptz   NOT NULL,
    actualizado_en timestamptz   NOT NULL,
    CONSTRAINT uq_variante_sku UNIQUE (sku),
    CONSTRAINT uq_variante_combinacion UNIQUE (producto_id, talla_id, color_id)
);

CREATE TABLE imagen (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id bigint       NOT NULL REFERENCES producto (id),
    color_id    bigint       REFERENCES color (id),   -- cada imagen pertenece a un color (D3)
    clave       varchar(255) NOT NULL,                -- ruta en el almacenamiento
    orden       integer      NOT NULL DEFAULT 0,
    principal   boolean      NOT NULL DEFAULT false,
    ancho       integer,
    alto        integer
);
CREATE UNIQUE INDEX uq_imagen_principal ON imagen (producto_id) WHERE principal;
CREATE INDEX ix_imagen_producto ON imagen (producto_id, orden);

CREATE TABLE guia_tallas (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id bigint NOT NULL REFERENCES categoria (id),
    tabla        jsonb  NOT NULL,
    nota         text,
    CONSTRAINT uq_guia_tallas_categoria UNIQUE (categoria_id)
);

CREATE TABLE tramo_descuento (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id      bigint       REFERENCES producto (id),   -- NULL = política global
    unidades_minimas integer      NOT NULL,
    porcentaje       numeric(5,2) NOT NULL,
    CONSTRAINT ck_tramo_porcentaje CHECK (porcentaje BETWEEN 0 AND 50)
);
CREATE UNIQUE INDEX uq_tramo_unidades ON tramo_descuento (producto_id, unidades_minimas) NULLS NOT DISTINCT;

-- Interruptor global de descuentos (fila única)
CREATE TABLE configuracion_descuento (
    id     bigint  PRIMARY KEY,
    activo boolean NOT NULL,
    CONSTRAINT ck_configuracion_descuento_unica CHECK (id = 1)
);

-- ============================ Módulo inventario ============================

CREATE TABLE stock (
    variante_id    bigint      PRIMARY KEY REFERENCES variante (id),
    fisico         integer     NOT NULL DEFAULT 0,
    reservado      integer     NOT NULL DEFAULT 0,
    minimo         integer,                      -- NULL = usa configuracion_inventario.stock_minimo_por_defecto
    actualizado_en timestamptz NOT NULL DEFAULT now(),
    version        integer     NOT NULL DEFAULT 0,
    CONSTRAINT ck_stock_cantidades CHECK (fisico >= 0 AND reservado >= 0 AND reservado <= fisico)
);

CREATE TABLE movimiento_stock (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variante_id  bigint       NOT NULL REFERENCES variante (id),
    tipo         varchar(20)  NOT NULL,
    cantidad     integer      NOT NULL,           -- con signo
    saldo_fisico integer      NOT NULL,
    motivo       varchar(255),
    usuario_id   uuid,                            -- NULL = sistema
    referencia   varchar(100),                    -- código de pedido, etc.
    creado_en    timestamptz  NOT NULL,
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN ('ENTRADA', 'AJUSTE', 'VENTA', 'REINGRESO'))
);
CREATE INDEX ix_movimiento_variante_fecha ON movimiento_stock (variante_id, creado_en DESC);

CREATE TABLE reserva (
    pedido_id      uuid        PRIMARY KEY,
    estado         varchar(20) NOT NULL,
    expira_en      timestamptz NOT NULL,
    creado_en      timestamptz NOT NULL,
    actualizado_en timestamptz NOT NULL,
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('ACTIVA', 'CONFIRMADA', 'LIBERADA', 'EXPIRADA', 'REINGRESADA'))
);
CREATE INDEX ix_reserva_activas_expiracion ON reserva (expira_en) WHERE estado = 'ACTIVA';

CREATE TABLE reserva_item (
    pedido_id   uuid    NOT NULL REFERENCES reserva (pedido_id),
    variante_id bigint  NOT NULL REFERENCES variante (id),
    cantidad    integer NOT NULL,
    PRIMARY KEY (pedido_id, variante_id),
    CONSTRAINT ck_reserva_item_cantidad CHECK (cantidad > 0)
);

-- Fila única; la edita el backoffice (pestaña Parámetros, SPEC-3) pero el dato lo guarda catalog
CREATE TABLE configuracion_inventario (
    id                       bigint  PRIMARY KEY,
    stock_minimo_por_defecto integer NOT NULL,
    margen_reserva_minutos   integer NOT NULL,
    CONSTRAINT ck_configuracion_inventario_unica CHECK (id = 1),
    CONSTRAINT ck_stock_minimo_por_defecto CHECK (stock_minimo_por_defecto BETWEEN 0 AND 999),
    CONSTRAINT ck_margen_reserva CHECK (margen_reserva_minutos BETWEEN 0 AND 30)
);

-- ============================ Eventos (ADR-009) ============================
-- Tipos que espera fitstore-common (infraestructura 10.3)

CREATE TABLE outbox_evento (
    id           uuid         PRIMARY KEY,
    tipo         varchar(100) NOT NULL,
    agregado_id  varchar(64)  NOT NULL,
    payload      jsonb        NOT NULL,
    creado_en    timestamptz  NOT NULL,
    publicado_en timestamptz
);
CREATE INDEX ix_outbox_pendientes ON outbox_evento (creado_en) WHERE publicado_en IS NULL;

CREATE TABLE evento_procesado (
    evento_id    uuid        PRIMARY KEY,
    procesado_en timestamptz NOT NULL
);
